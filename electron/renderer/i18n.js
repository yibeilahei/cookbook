const UI_LOCALE_CODES = { english: "en", japanese: "ja", chinese: "zh", korean: "ko" };

/** Map the OS/browser locale (e.g. "ja-JP", "zh-Hant", "en-US") to one of
 *  the UI language buckets above, defaulting to "english". Independent of
 *  the book-content "Language" Settings field -- the UI chrome always
 *  follows the OS locale, regardless of what's picked there. */
function detectUiLanguage() {
  const locale = (navigator.language || "en").toLowerCase();
  if (locale.startsWith("ja")) return "japanese";
  if (locale.startsWith("zh")) return "chinese";
  if (locale.startsWith("ko")) return "korean";
  return "english";
}

const uiLanguage = detectUiLanguage();
const uiStrings = STRINGS[uiLanguage] || STRINGS.english;

/** Look up `key` in the current UI language (falling back to English),
 *  substituting any `{name}` placeholders from `vars`. */
function t(key, vars) {
  let str = uiStrings[key] != null ? uiStrings[key] : STRINGS.english[key];
  if (str == null) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{${k}}`).join(v);
    }
  }
  return str;
}

